byte abs_diff(byte a, byte b) {
  return (a > b) ? (byte)(a - b) : (byte)(b - a);
}

byte glyph(char c) {
  if (c == ' ') return 0;
  if (c >= '0' && c <= '9') return (byte)(1 + (c - '0'));
  switch (c) {
    case 'A': return 11; case 'C': return 12; case 'E': return 13;
    case 'F': return 14; case 'G': return 15; case 'H': return 16;
    case 'I': return 17; case 'K': return 18; case 'L': return 19;
    case 'M': return 20; case 'N': return 21; case 'O': return 22;
    case 'P': return 23; case 'R': return 24; case 'S': return 25;
    case 'T': return 26; case 'U': return 27; case 'V': return 28;
    case 'W': return 29; case 'X': return 30; case 'D': return 31;
    case '-': return 32; case '!': return 33; case '/': return 34;
    default: return 0;
  }
}

void put_str(byte x, byte y, const char* s) {
  while (*s) set_bkg_tile_xy(x++, y, glyph(*s++));
}

void put_digit(byte x, byte y, byte d) {
  set_bkg_tile_xy(x, y, (byte)(1 + (d % 10)));
}

void clrscr(void) {
  byte x, y;
  for (y = 0; y < 32; y++)
    for (x = 0; x < 32; x++)
      set_bkg_tile_xy(x, y, 0);
}

void hide_all_sprites(void) {
  byte i;
  for (i = 0; i < 40; i++) move_sprite(i, 0, 0);
}

void read_controls(void) {
  byte j = joypad();
  joy_left = (j & J_LEFT) != 0;
  joy_right = (j & J_RIGHT) != 0;
  joy_fire = (j & J_A) != 0;
  joy_start = (j & J_START) != 0;
}

void psg_init(void) {
  NR52_REG = 0x80;
  NR50_REG = 0x77;
  NR51_REG = 0xFF;
  NR10_REG = 0x00;
}

void sfx_off(void) {
  sfx_timer = 0;
  sfx_kind = 0;
  NR12_REG = 0x00;
  NR14_REG = 0x80;
  NR22_REG = 0x00;
  NR24_REG = 0x80;
}

void beep(word per, byte vol, byte len) {
  /* ch1 one-shot */
  NR10_REG = 0x00;
  NR11_REG = 0x80;
  NR12_REG = (byte)((vol << 4) | 0x01);
  NR13_REG = (byte)(per & 0xff);
  NR14_REG = (byte)(0x80 | ((per >> 8) & 0x07));
  sfx_timer = len;
}

void play_sfx(byte id) {
  sfx_kind = id;
  if (id == 4) death_phase = 0;
  switch (id) {
  case 1: beep(0x6C0, 10, 3); break;   /* waka hi */
  case 2: beep(0x650, 9, 3); break;    /* waka lo */
  case 3: beep(0x700, 12, 12); break;  /* eat ghost */
  case 4: beep(0x480, 12, 40); break;  /* death */
  case 6: beep(0x720, 11, 8); break;   /* power */
  default: sfx_off(); break;
  }
}

void tick_sfx(void) {
  if (!sfx_timer) return;
  --sfx_timer;
  if (!sfx_timer && sfx_kind == 4) {
    death_phase++;
    if (death_phase < 4) {
      beep((word)(0x480 - death_phase * 0x40), 10, 10);
      sfx_kind = 4;
    } else {
      death_phase = 0;
      sfx_kind = 0;
    }
  }
}

void wait_vblank(void) {
  wait_vbl_done();
  tick_sfx();
}

void wait_frames(byte n) {
  while (n--) wait_vblank();
}

void wait_for_button(void) {
  read_controls();
  while (!joy_fire && !joy_start) { wait_vblank(); read_controls(); }
  while (joy_fire || joy_start) { wait_vblank(); read_controls(); }
}

void draw_hud(void) {
  put_str(0, 0, "PAKU PAKU");
  put_str(0, 1, "SCORE");
  put_digit(6, 1, (byte)((score / 1000) % 10));
  put_digit(7, 1, (byte)((score / 100) % 10));
  put_digit(8, 1, (byte)((score / 10) % 10));
  put_digit(9, 1, (byte)(score % 10));
  put_str(12, 1, "X");
  put_digit(13, 1, multiplier > 9 ? 9 : multiplier);
  put_str(0, 17, "A=TURN");
}

void draw_corridor(void) {
  byte x;
  for (x = 0; x < 20; x++) {
    set_bkg_tile_xy(x, ROW_ABOVE, T_WALL_ABOVE);
    set_bkg_tile_xy(x, DOT_TILE_Y, 0);
    set_bkg_tile_xy(x, ROW_BELOW, T_WALL_BELOW);
  }
}

void add_dots(void) {
  byte i, pi;
  pi = (player_x > 80) ? (byte)(1 + (rand8() % 7)) : (byte)(10 + (rand8() % 7));
  for (i = 0; i < NUM_DOTS; i++) {
    dots[i].tx = (byte)(i + 1);
    dots[i].active = 1;
    dots[i].is_power = (i == pi);
  }
  if (multiplier < 99) multiplier++;
}

void draw_dots(void) {
  byte i;
  for (i = 0; i < NUM_DOTS; i++) {
    if (!dots[i].active) {
      set_bkg_tile_xy(dots[i].tx, DOT_TILE_Y, 0);
      continue;
    }
    if (dots[i].is_power) {
      if ((anim_ticks >> 3) & 1)
        set_bkg_tile_xy(dots[i].tx, DOT_TILE_Y, T_POWER);
      else
        set_bkg_tile_xy(dots[i].tx, DOT_TILE_Y, 0);
    } else {
      set_bkg_tile_xy(dots[i].tx, DOT_TILE_Y, T_DOT);
    }
  }
}

void collect_dots(void) {
  byte i, ptx;
  ptx = (byte)((player_x + 8) >> 3);
  if (ptx < 1) ptx = 1;
  if (ptx > NUM_DOTS) ptx = NUM_DOTS;
  for (i = 0; i < NUM_DOTS; i++) {
    if (!dots[i].active) continue;
    if (dots[i].tx != ptx) continue;
    dots[i].active = 0;
    set_bkg_tile_xy(dots[i].tx, DOT_TILE_Y, 0);
    if (dots[i].is_power) {
      play_sfx(6);
      if (!enemy_eye_vx) power_ticks = 200;
    } else {
      waka ^= 1;
      play_sfx(waka ? 1 : 2);
    }
    score += multiplier;
  }
}

byte dots_left(void) {
  byte i, n = 0;
  for (i = 0; i < NUM_DOTS; i++)
    if (dots[i].active) n++;
  return n;
}

byte pac_frame(void) {
  byte ai = (byte)(anim_ticks & 3);
  if (ai == 0) return SP_OPEN;
  if (ai == 1) return SP_MID;
  if (ai == 2) return SP_CLOSED;
  return SP_MID;
}

void put_actor16(byte i0, byte frame, byte flip, byte prop, byte x, byte y) {
  /* Two 8×16 sprites = one 16×16 arcade sprite; swap halves when flipped. */
  byte i1 = (byte)(i0 + 1);
  byte p = prop;
  byte oam0, oam1;
  if (flip) p |= S_FLIPX;
  set_sprite_tile(i0, frame);
  set_sprite_tile(i1, (byte)(frame + 2));
  set_sprite_prop(i0, p);
  set_sprite_prop(i1, p);
  if (flip) {
    oam0 = (byte)(x + 16);
    oam1 = (byte)(x + 8);
  } else {
    oam0 = (byte)(x + 8);
    oam1 = (byte)(x + 16);
  }
  /* Hide if past the right edge (OAM X wraps). */
  if (x > 152) {
    move_sprite(i0, 0, 0);
    move_sprite(i1, 0, 0);
    return;
  }
  move_sprite(i0, oam0, (byte)(y + 16));
  move_sprite(i1, oam1, (byte)(y + 16));
}

void draw_actors(void) {
  byte ghost, gprop, pflip, gflip;
  sbyte evx;

  pflip = (player_vx < 0) ? 1 : 0;
  put_actor16(0, pac_frame(), pflip, 0, player_x, CORRIDOR_Y);

  if (enemy_eye_vx) {
    ghost = SP_EYES;
    gflip = (enemy_eye_vx < 0) ? 1 : 0;
    gprop = 0;
  } else if (power_ticks) {
    ghost = ((anim_ticks >> 1) & 1) ? SP_SCARED1 : SP_SCARED0;
    gflip = 0;
    gprop = 0;
    /* blink near end of power */
    if (power_ticks < 60 && (anim_ticks & 0x08)) {
      move_sprite(2, 0, 0);
      move_sprite(3, 0, 0);
      return;
    }
  } else {
    ghost = ((anim_ticks >> 1) & 1) ? SP_GHOST1 : SP_GHOST0;
    evx = (player_x > enemy_x) ? 1 : -1;
    gflip = (evx < 0) ? 1 : 0;
    gprop = 0;
  }
  put_actor16(2, ghost, gflip, gprop, enemy_x, CORRIDOR_Y);
}

void title_screen(void) {
  byte x;
  clrscr();
  hide_all_sprites();
  move_bkg(0, 0);
  /* corridor stripe behind the demo sprites */
  for (x = 0; x < 20; x++) {
    set_bkg_tile_xy(x, 6, T_WALL_ABOVE);
    set_bkg_tile_xy(x, 7, 0);
    set_bkg_tile_xy(x, 8, T_WALL_BELOW);
  }
  put_str(5, 2, "PAKU PAKU");
  put_actor16(0, SP_OPEN, 0, 0, 52, 48);
  put_actor16(2, SP_GHOST0, 0, 0, 92, 48);
  put_str(4, 11, "A TO TURN");
  put_str(2, 13, "EAT DOTS  EAT GHOST");
  put_str(4, 16, "PRESS START");
  wait_for_button();
  sfx_off();
}

void show_game_over(void) {
  byte frame_i, t, frame;
  hide_all_sprites();
  put_actor16(0, SP_OPEN, 0, 0, player_x, CORRIDOR_Y);
  play_sfx(4);
  /* Arcade: 11 frames × 8 vblanks */
  for (frame_i = 0; frame_i < SP_DEATH_N; frame_i++) {
    frame = (byte)(SP_DEATH0 + (byte)(frame_i * 4));
    for (t = 0; t < 8; t++) {
      put_actor16(0, frame, 0, 0, player_x, CORRIDOR_Y);
      wait_vblank();
      read_controls();
      if (joy_fire || joy_start) goto death_done;
    }
  }
death_done:
  hide_all_sprites();
  put_str(5, 7, "GAME OVER");
  put_str(4, 10, "PRESS START");
  wait_for_button();
  sfx_off();
}

void reset_round(void) {
  player_x = 48;
  player_vx = 1;
  enemy_x = 128;
  enemy_eye_vx = 0;
  power_ticks = 0;
  anim_ticks = 0;
  btn_prev = 1;
  game_over = 0;
  waka = 0;
  sfx_off();
  draw_corridor();
  add_dots();
}

void game_loop(void) {
  byte btn;
  sbyte evx;
  byte espd;

  clrscr();
  hide_all_sprites();
  move_bkg(0, 0);
  draw_corridor();
  draw_hud();
  reset_round();

  while (!game_over) {
    wait_vblank();
    anim_ticks++;
    read_controls();

    btn = (joy_fire || joy_start) ? 1 : 0;
    if (btn && !btn_prev) player_vx = (sbyte)-player_vx;
    btn_prev = btn;
    if (joy_left) player_vx = -1;
    if (joy_right) player_vx = 1;

    /* Same wrap as pacman pakupaku.c */
    player_x = (byte)(player_x + player_vx * PLAYER_SPD);
    if (player_x < 4) player_x = FIELD_MAX;
    else if (player_x > FIELD_MAX) player_x = 4;

    collect_dots();
    if (!dots_left()) add_dots();

    /* Ghost AI — identical rules to presets/pacman/pakupaku.c */
    if (enemy_eye_vx) {
      evx = enemy_eye_vx;
      espd = 3;
    } else if (power_ticks) {
      evx = (player_x > enemy_x) ? (sbyte)-1 : 1;
      espd = 1;
    } else {
      evx = (player_x > enemy_x) ? 1 : -1;
      espd = 2;
    }
    if (evx > 0) {
      if (enemy_x < FIELD_MAX - 2) enemy_x = (byte)(enemy_x + espd);
      else if (enemy_eye_vx) enemy_eye_vx = 0;
    } else {
      if (enemy_x > 6) enemy_x = (byte)(enemy_x - espd);
      else if (enemy_eye_vx) enemy_eye_vx = 0;
    }

    if (!enemy_eye_vx && abs_diff(player_x, enemy_x) < HIT_DIST) {
      if (power_ticks) {
        play_sfx(3);
        score += (word)(10 * (multiplier ? multiplier : 1));
        enemy_eye_vx = (player_x > 80) ? (sbyte)-1 : 1;
        power_ticks = 0;
        if (multiplier < 99) multiplier++;
      } else {
        game_over = 1;
      }
    }

    if (power_ticks) power_ticks--;

    draw_dots();
    draw_hud();
    draw_actors();
  }
}

void setup_graphics(void) {
  DISPLAY_OFF;
  set_bkg_1bpp_data(0, 35, font_1bpp);
  set_bkg_data(BKG_BASE, 4, bkg_tiles);
  set_sprite_data(SPR_BASE, SPR_TILE_COUNT, sprite_tiles);
  SPRITES_8x16;
  BGP_REG = 0xE4;
  OBP0_REG = 0xE4;
  OBP1_REG = 0xE4;
  psg_init();
  HIDE_WIN;
  SHOW_BKG;
  SHOW_SPRITES;
  DISPLAY_ON;
}

void main(void) {
  setup_graphics();
  score = 0;
  multiplier = 0;
  while (1) {
    title_screen();
    score = 0;
    multiplier = 0;
    game_loop();
    show_game_over();
  }
}
