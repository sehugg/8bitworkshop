/* load the font into BG tile data (call with the LCD off) */
static void font_init(void) {
  set_bkg_data(FONT_TILE_BASE, FONT_NUM_TILES, font_tiles);
}

/* write a string to the tile map; tile index == ASCII code */
static void put_str(uint8_t x, uint8_t y, const char* s) {
  set_bkg_tiles(x, y, strlen(s), 1, (uint8_t*)s);
}

/* write a single character to the tile map */
static void put_char(uint8_t x, uint8_t y, char c) {
  set_bkg_tiles(x, y, 1, 1, (uint8_t*)&c);
}

