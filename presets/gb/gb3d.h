// Quarter-square multiplication:
//   a*b = ((a+b)^2 - (a-b)^2) / 4
// With a table of floor(n^2/4), an 8x8 signed multiply costs two table
// lookups and a subtraction. (The floors cancel: a+b and a-b are always
// both even or both odd.)
int16_t mul8(int8_t a, int8_t b) {
  return sq4[256 + a + b] - sq4[256 + a - b];
}

// Perspective divide by table: recip[z] = 24576 / z, built once at boot
// with the slow library divide. At run time x/z becomes x * recip[z].
uint16_t recip[256];

#define ZDIST 160   // distance from eye to cube center
#define CX (TB_W/2)
#define CY (TB_H/2)

// cube corners
const int8_t cube[8][3] = {
  {-32,-32,-32}, { 32,-32,-32}, { 32, 32,-32}, {-32, 32,-32},
  {-32,-32, 32}, { 32,-32, 32}, { 32, 32, 32}, {-32, 32, 32},
};
// 12 edges as pairs of corner indices
const uint8_t edges[12][2] = {
  {0,1},{1,2},{2,3},{3,0}, {4,5},{5,6},{6,7},{7,4}, {0,4},{1,5},{2,6},{3,7},
};

uint8_t sx[8], sy[8];   // projected corners

void transform(uint8_t ay, uint8_t ax) {
  int8_t sa = sin_tab[ay], ca = sin_tab[(uint8_t)(ay + 64)];
  int8_t sb = sin_tab[ax], cb = sin_tab[(uint8_t)(ax + 64)];
  uint8_t i;
  for (i = 0; i < 8; i++) {
    int8_t x = cube[i][0], y = cube[i][1], z = cube[i][2];
    int8_t x1, z1, y2, z2;
    uint8_t zz;
    // rotate around Y (results scaled back down by 127 ~ >>7)
    x1 = (mul8(x, ca) - mul8(z, sa)) >> 7;
    z1 = (mul8(x, sa) + mul8(z, ca)) >> 7;
    // rotate around X
    y2 = (mul8(y, cb) - mul8(z1, sb)) >> 7;
    z2 = (mul8(y, sb) + mul8(z1, cb)) >> 7;
    // project: screen = center + x * (96 / z)
    zz = ZDIST + z2;
    sx[i] = CX + (int8_t)(((int16_t)x1 * (int16_t)recip[zz]) >> 8);
    sy[i] = CY + (int8_t)(((int16_t)y2 * (int16_t)recip[zz]) >> 8);
  }
}

// call once at startup: fill recip[] using the (slow) library divide
void gb3d_init(void) {
  uint16_t z;
  for (z = 1; z < 256; z++) recip[z] = 24576U / z;
}

