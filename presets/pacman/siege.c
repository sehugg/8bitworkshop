#define COLS 28
#define ROWS 36
#define PLAY_Y0 2
#define PLAY_Y1 33

#define T_SOLID  0x11
#define T_CHECK  0x12

typedef struct {
  byte x;
  byte y;
  byte dir;
  byte score;
  byte head_tile;
  byte tail_tile;
  byte head_pal;
  byte tail_pal;
  byte collided;
  byte human;
} Player;

Player players[2];

byte frames_per_move;
byte gameover;
word rnd_state;

#define START_SPEED 12
#define MAX_SPEED 5
#define MAX_SCORE 7

typedef enum { D_RIGHT, D_DOWN, D_LEFT, D_UP } dir_t;
static const sbyte DIR_X[4] = { 1, 0, -1, 0 };
static const sbyte DIR_Y[4] = { 0, 1, 0, -1 };

byte rand8(void) {
  rnd_state = rnd_state * 17 + 53;
  return (byte)(rnd_state >> 8);
}

void delay_frames(byte n) {
  while (n--) wait_vblank();
}

void draw_box(byte x, byte y, byte x2, byte y2, byte pal) {
  byte xi, yi;
  poke_tile(x, y, T_WALL_TL, pal);
  poke_tile(x2, y, T_WALL_TR, pal);
  poke_tile(x, y2, T_WALL_BL, pal);
  poke_tile(x2, y2, T_WALL_BR, pal);
  for (xi = x + 1; xi < x2; xi++) {
    poke_tile(xi, y, T_WALL_H, pal);
    poke_tile(xi, y2, T_WALL_H, pal);
  }
  for (yi = y + 1; yi < y2; yi++) {
    poke_tile(x, yi, T_WALL_V, pal);
    poke_tile(x2, yi, T_WALL_V, pal);
  }
}

void draw_playfield(void) {
  draw_box(0, PLAY_Y0, COLS - 1, PLAY_Y1, PAL_BLUE);
  put_string(0, 0, "P1", PAL_YELLOW);
  put_digit(3, 0, players[0].score, PAL_YELLOW);
  put_string(22, 0, "P2", PAL_PINK);
  put_digit(25, 0, players[1].score, PAL_PINK);
}

void init_game(void) {
  players[0].score = 0;
  players[1].score = 0;
  players[0].head_tile = '1';
  players[1].head_tile = '2';
  players[0].tail_tile = T_SOLID;
  players[1].tail_tile = T_CHECK;
  players[0].head_pal = PAL_YELLOW;
  players[0].tail_pal = PAL_YELLOW;
  players[1].head_pal = PAL_PINK;
  players[1].tail_pal = PAL_PINK;
  players[0].human = 1;
  players[1].human = 0;
  frames_per_move = START_SPEED;
  rnd_state = 0x1234;
}

void reset_players(void) {
  players[0].x = 5;
  players[0].y = 8;
  players[0].dir = D_RIGHT;
  players[1].x = 22;
  players[1].y = 28;
  players[1].dir = D_LEFT;
  players[0].collided = 0;
  players[1].collided = 0;
}

void draw_player(Player* p) {
  poke_tile(p->x, p->y, p->head_tile, p->head_pal);
}

byte cell_blocked(byte x, byte y) {
  byte t;
  if (x >= COLS || y < PLAY_Y0 || y > PLAY_Y1) return 1;
  t = peek_tile(x, y);
  return t != T_BLANK;
}

void move_player(Player* p) {
  poke_tile(p->x, p->y, p->tail_tile, p->tail_pal);
  p->x += DIR_X[p->dir];
  p->y += DIR_Y[p->dir];
  if (cell_blocked(p->x, p->y))
    p->collided = 1;
  else
    draw_player(p);
}

void human_control(Player* p) {
  byte dir = 0xff;
  if (!p->human) return;
  if (LEFT1) dir = D_LEFT;
  if (RIGHT1) dir = D_RIGHT;
  if (UP1) dir = D_UP;
  if (DOWN1) dir = D_DOWN;
  if (dir != 0xff && dir != (p->dir ^ 2))
    p->dir = dir;
}

byte ai_try_dir(Player* p, byte dir, byte shift) {
  byte x, y;
  dir &= 3;
  x = p->x + (DIR_X[dir] << shift);
  y = p->y + (DIR_Y[dir] << shift);
  if (!cell_blocked(x, y)) {
    p->dir = dir;
    return 1;
  }
  return 0;
}

void ai_control(Player* p) {
  byte dir;
  if (p->human) return;
  dir = p->dir;
  if (!ai_try_dir(p, dir, 0)) {
    ai_try_dir(p, (byte)(dir + 1), 0);
    ai_try_dir(p, (byte)(dir - 1), 0);
  } else {
    if (ai_try_dir(p, (byte)(dir - 1), 0))
      ai_try_dir(p, (byte)(dir - 1), (byte)(1 + (rand8() & 3)));
    if (ai_try_dir(p, (byte)(dir + 1), 0))
      ai_try_dir(p, (byte)(dir + 1), (byte)(1 + (rand8() & 3)));
    ai_try_dir(p, dir, rand8() & 3);
  }
}

void flash_colliders(void) {
  byte i;
  for (i = 0; i < 40; i++) {
    wait_vblank();
    if (players[0].collided)
      poke_tile(players[0].x, players[0].y, players[0].head_tile,
                (i & 1) ? PAL_WHITE : PAL_YELLOW);
    if (players[1].collided)
      poke_tile(players[1].x, players[1].y, players[1].head_tile,
                (i & 1) ? PAL_WHITE : PAL_PINK);
  }
}

void make_move(void) {
  byte i;
  for (i = 0; i < frames_per_move; i++) {
    human_control(&players[0]);
    wait_vblank();
  }
  ai_control(&players[0]);
  ai_control(&players[1]);
  move_player(&players[1]);
  move_player(&players[0]);
}

void declare_winner(byte winner) {
  byte i;
  clrscr(0);
  hide_all_sprites();
  for (i = 0; i < 8; i++) {
    draw_box(i, i + 2, (byte)(COLS - 1 - i), (byte)(PLAY_Y1 - i), PAL_CYAN);
    delay_frames(2);
  }
  put_string(8, 16, "WINNER", PAL_YELLOW);
  put_string(8, 18, "PLAYER", PAL_WHITE);
  poke_tile(15, 18, (byte)('1' + winner), PAL_YELLOW);
  delay_frames(90);
  gameover = 1;
}

void play_round(void) {
  reset_players();
  clrscr(0);
  hide_all_sprites();
  draw_playfield();
  draw_player(&players[0]);
  draw_player(&players[1]);
  while (1) {
    make_move();
    if (players[0].collided || players[1].collided) break;
  }
  flash_colliders();
  sound_beep(players[0].collided ? 0x800 : 0x1400, 3);
  if (players[0].collided) players[1].score++;
  if (players[1].collided) players[0].score++;
  if (frames_per_move > MAX_SPEED) frames_per_move--;
  if (players[0].score != players[1].score) {
    if (players[0].score >= MAX_SCORE)
      declare_winner(0);
    else if (players[1].score >= MAX_SCORE)
      declare_winner(1);
  }
}

void play_game(void) {
  gameover = 0;
  init_game();
  while (!gameover)
    play_round();
}

void main(void) {
  video_framecount = 0;
  pac_irq_enable();
  sound_enable = 1;
  flip_screen = 0;
  watchdog = 0;

  clrscr(0);
  hide_all_sprites();
  put_string(8, 14, "SIEGE", PAL_YELLOW);
  put_string(4, 18, "PRESS START", PAL_CYAN);
  while (!START1) {
    wait_vblank();
    watchdog = 0;
  }
  play_game();
  while (1) {
    wait_vblank();
    watchdog = 0;
  }
}

