/*
 * Climber — platform / ladder game for Pac-Man hardware.
 * Ported/simplified from presets/coleco/climber.c
 *
 * Controls: Left/Right walk, Up/Down climb, Space jump, Start to begin.
 * Climb to the TOP floor (level counter hits the last stage) to win.
 *
 * Graphics for this file are appended at the bottom (private copy).
 * Climber frames + floor/ladder tiles are converted from presets/coleco/climber.c
 * (walk/climb/jump/fall + HW flipX for facing / climb bob).
 */
//#link "pacman_common.c"
#include "pacman_common.h"

#define COLS 28
#define VIEW_H 28
#define VIEW_Y0 4
#define MAX_LEVELS 12
#define GAPSIZE 3
#define MAX_ACTORS 4
#define TOP_LEVEL (MAX_LEVELS - 1)

#define T_FLOOR  0x15
#define T_LADDER 0x16
#define T_BRICK  0x11

/* Sprite ROM frames (from Coleco climber.c) */
#define SP_WALK0  0
#define SP_WALK1  1
#define SP_CLIMB0 2
#define SP_CLIMB1 3
#define SP_JUMP   4
#define SP_FALL   5
#define FLIP_X    2

typedef struct {
  byte ypos;
  byte height;
  byte gap;
  byte ladder1;
  byte ladder2;
} Level;

Level levels[MAX_LEVELS];
byte scroll_y;
byte world_h;
word rnd_state;

typedef enum { INACTIVE, WALKING, CLIMBING, JUMPING, FALLING } ActorState;

typedef struct {
  word yy;
  byte x;
  byte level;
  byte state;
  byte dir;
  byte onscreen;
  sbyte xvel;
  sbyte yvel;
} Actor;

Actor actors[MAX_ACTORS];

/* Set when leaving a ladder; cleared when UP is released — blocks chain-climbing. */
byte climb_up_lock;

byte rand8(void) {
  rnd_state = rnd_state * 17 + 53;
  return (byte)(rnd_state >> 8);
}

byte rndint(byte lo, byte hi) {
  return lo + (rand8() % (byte)(hi - lo + 1));
}

byte iabs8(sbyte x) {
  return x >= 0 ? (byte)x : (byte)(-x);
}

byte dist8(word a, word b) {
  return (a > b) ? (byte)(a - b) : (byte)(b - a);
}

byte ladder_in_gap(byte ladder, byte gap) {
  return gap && ladder >= gap && ladder < gap + GAPSIZE;
}

void make_levels(void) {
  byte i;
  byte y = 0;
  Level* prev = &levels[0];
  rnd_state = 0xC1A1;
  for (i = 0; i < MAX_LEVELS; i++) {
    Level* lev = &levels[i];
    lev->height = rndint(3, 5);
    lev->ladder1 = rndint(2, 11);
    lev->ladder2 = rndint(14, 24);
    do {
      lev->gap = (i > 0 && i < TOP_LEVEL) ? rndint(0, 22) : 0;
    } while (ladder_in_gap(prev->ladder1, lev->gap) ||
             ladder_in_gap(prev->ladder2, lev->gap));
    lev->ypos = y;
    y += lev->height;
    prev = lev;
  }
  /* Top stage: solid floor, no gaps/ladders — reaching it wins */
  levels[TOP_LEVEL].height = 4;
  levels[TOP_LEVEL].gap = 0;
  levels[TOP_LEVEL].ladder1 = 0;
  levels[TOP_LEVEL].ladder2 = 0;
  levels[TOP_LEVEL].ypos = y - levels[TOP_LEVEL].height;
  /* Ensure previous stage still reaches the top floor */
  {
    byte prev_h = levels[TOP_LEVEL - 1].height;
    levels[TOP_LEVEL].ypos = levels[TOP_LEVEL - 1].ypos + prev_h;
  }
  world_h = levels[TOP_LEVEL].ypos + levels[TOP_LEVEL].height;
}

byte max_scroll_y(void) {
  if (world_h <= VIEW_H) return 0;
  return world_h - VIEW_H;
}

word get_floor_yy(byte level) {
  return (word)levels[level].ypos * 8 + 8;
}

word get_ceiling_yy(byte level) {
  return (word)(levels[level].ypos + levels[level].height) * 8 + 8;
}

byte is_in_gap(byte x, byte gap) {
  byte x1;
  if (!gap) return 0;
  x1 = gap * 8;
  return (x > x1 && x < x1 + GAPSIZE * 8 - 4);
}

void create_actors_on_level(byte li) {
  byte ai = (li % (MAX_ACTORS - 1)) + 1;
  Actor* a = &actors[ai];
  if (!a->onscreen && li > 0 && li < TOP_LEVEL) {
    a->state = WALKING;
    a->x = levels[li].ladder1 * 8 - 4;
    a->yy = get_floor_yy(li);
    a->level = li;
    a->dir = rand8() & 1;
    a->onscreen = 1;
  }
}

void draw_level_line(byte screen_y) {
  byte x;
  byte world_y = screen_y + scroll_y;
  byte row = VIEW_Y0 + (VIEW_H - 1) - screen_y;
  byte i;
  byte drawn = 0;

  for (i = 0; i < MAX_LEVELS; i++) {
    Level* lev = &levels[i];
    byte dy = world_y - lev->ypos;
    if (dy < lev->height) {
      drawn = 1;
      if (dy == 0) {
        for (x = 0; x < COLS; x++) {
          if (lev->gap && x >= lev->gap && x < lev->gap + GAPSIZE)
            poke_tile(x, row, T_BLANK, 0);
          else
            poke_tile(x, row, T_FLOOR, i == TOP_LEVEL ? PAL_YELLOW : PAL_BLUE);
        }
      } else {
        for (x = 0; x < COLS; x++) poke_tile(x, row, T_BLANK, 0);
        poke_tile(0, row, T_BRICK, PAL_BLUE);
        poke_tile(COLS - 1, row, T_BRICK, PAL_BLUE);
        if (lev->ladder1)
          poke_tile(lev->ladder1, row, T_LADDER, PAL_ORANGE);
        if (lev->ladder2)
          poke_tile(lev->ladder2, row, T_LADDER, PAL_ORANGE);
      }
      if (screen_y == 0 || screen_y == VIEW_H - 1)
        create_actors_on_level(i);
      break;
    }
  }
  if (!drawn) {
    for (x = 0; x < COLS; x++) poke_tile(x, row, T_BLANK, 0);
  }
}

void draw_hud(void) {
  put_string(0, 0, "CLIMBER", PAL_CYAN);
  put_string(10, 0, "LV", PAL_WHITE);
  put_digit(13, 0, actors[0].level / 10, PAL_YELLOW);
  put_digit(14, 0, actors[0].level % 10, PAL_YELLOW);
  put_string(17, 0, "GOAL", PAL_PINK);
  put_digit(22, 0, TOP_LEVEL / 10, PAL_PINK);
  put_digit(23, 0, TOP_LEVEL % 10, PAL_PINK);
}

void draw_screen(void) {
  byte y;
  for (y = 0; y < VIEW_H; y++) {
    draw_level_line(y);
    if ((y & 7) == 0) watchdog = 0;
  }
  draw_hud();
}

/* Return ladder tile pixel X if actor is on/near that ladder column, else 0. */
byte is_ladder_close(byte actor_x, byte ladder_pos) {
  byte lx;
  if (!ladder_pos) return 0;
  lx = ladder_pos * 8;
  /* Mount X is lx-4 (art is left-biased in the 16px sprite). Accept near that. */
  if ((byte)(actor_x + 8 - lx) < 16) return lx;
  return 0;
}

byte get_closest_ladder(byte px, byte li) {
  byte x1, x2;
  if (li >= MAX_LEVELS) return 0;
  x1 = is_ladder_close(px, levels[li].ladder1);
  x2 = is_ladder_close(px, levels[li].ladder2);
  if (x1 && x2) {
    byte c1 = x1 + 4;
    byte c2 = x2 + 4;
    byte mid = px + 8; /* approx sprite center */
    return (iabs8((sbyte)(mid - c1)) <= iabs8((sbyte)(mid - c2))) ? x1 : x2;
  }
  if (x1) return x1;
  return x2;
}

byte mount_ladder(Actor* p, sbyte level_adjust) {
  byte x;
  byte li = (byte)(p->level + level_adjust);
  if (level_adjust < 0 && p->level == 0) return 0;
  x = get_closest_ladder(p->x, li);
  if (x) {
    /* Sprite content center ~8; ladder tile center lx+4 → draw at lx-4 */
    p->x = x - 4;
    p->state = CLIMBING;
    p->level = li;
    return 1;
  }
  return 0;
}

byte actor_shape(Actor* a) {
  switch (a->state) {
    case WALKING:
      return (a->x & 4) ? SP_WALK1 : SP_WALK0;
    case CLIMBING:
      /* Alternate baked frames — do not HW-flip (art is off-center). */
      return (a->yy & 4) ? SP_CLIMB1 : SP_CLIMB0;
    case JUMPING:
      return SP_JUMP;
    case FALLING:
      return SP_FALL;
    default:
      return SP_WALK0;
  }
}

byte actor_flip(Actor* a) {
  /* Facing only; climb uses a mirrored ROM frame instead of flipX. */
  if (a->state == CLIMBING) return 0;
  return a->dir ? FLIP_X : 0;
}

void draw_actors(void) {
  byte i;
  for (i = 0; i < MAX_ACTORS; i++) {
    Actor* a = &actors[i];
    int screen_py;
    byte sx, sy;
    if (a->state == INACTIVE) {
      hide_sprite(i);
      a->onscreen = 0;
      continue;
    }
    screen_py = (int)(a->yy) - (int)scroll_y * 8;
    sy = (byte)(VIEW_Y0 * 8 + (VIEW_H * 8 - 16) - screen_py);
    sx = a->x;
    if (screen_py < -16 || screen_py > VIEW_H * 8 + 8) {
      hide_sprite(i);
      a->onscreen = 0;
      continue;
    }
    set_sprite_ex(i, actor_shape(a),
                  i ? PAL_PINK : PAL_YELLOW, sx, sy, actor_flip(a));
    a->onscreen = 1;
  }
}

void refresh_screen(void) {
  draw_screen();
  draw_actors();
}

/* Keep player near vertical center; scroll as far as the tower allows. */
void keep_player_in_view(void) {
  Actor* p = &actors[0];
  byte maxs = max_scroll_y();
  byte changed = 0;
  int screen_py;
  byte target = VIEW_H * 4; /* center-ish in world pixels within view */

  for (;;) {
    screen_py = (int)p->yy - (int)scroll_y * 8;
    if (screen_py > (int)target + 16 && scroll_y < maxs) {
      scroll_y++;
      changed = 1;
      continue;
    }
    if (screen_py < (int)target - 24 && scroll_y > 0) {
      scroll_y--;
      changed = 1;
      continue;
    }
    break;
  }
  if (changed) refresh_screen();
}

void fall_down(Actor* a) {
  if (a->level == 0) return;
  a->level--;
  a->state = FALLING;
  a->xvel = 0;
  a->yvel = 0;
  sound_enable = 1;
  sound_voice(0, 0x600, 10, 3);
}

void move_actor(Actor* a, byte joy, byte do_scroll) {
  /* Lock is player-only (shared flag); enemies must not clear/set it. */
  if (do_scroll && !(joy & 0x01)) climb_up_lock = 0;

  switch (a->state) {
    case WALKING:
      if (joy & 0x10) {
        a->state = JUMPING;
        a->xvel = 0;
        a->yvel = 12;
        if (joy & 0x02) a->xvel = -1;
        if (joy & 0x04) a->xvel = 1;
        if (do_scroll) sound_beep(0x1400, 2);
      } else if (joy & 0x02) {
        if (a->x > 8) a->x--;
        a->dir = 1;
      } else if (joy & 0x04) {
        if (a->x < 208) a->x++;
        a->dir = 0;
      } else if ((joy & 0x01) && (!do_scroll || !climb_up_lock)) {
        mount_ladder(a, 0);
      } else if (joy & 0x08) {
        mount_ladder(a, -1);
      }
      break;
    case CLIMBING:
      if (joy & 0x01) {
        if (a->yy >= get_ceiling_yy(a->level)) {
          if (a->level < TOP_LEVEL) a->level++;
          a->yy = get_floor_yy(a->level);
          a->state = WALKING;
          if (do_scroll) climb_up_lock = 1;
        } else {
          a->yy += 2;
        }
      } else if (joy & 0x08) {
        if (a->yy <= get_floor_yy(a->level)) {
          a->state = WALKING;
        } else {
          a->yy -= 2;
        }
      }
      break;
    case JUMPING:
    case FALLING:
      a->x += a->xvel;
      if (a->x < 8) a->x = 8;
      if (a->x > 208) a->x = 208;
      a->yy += (a->yvel > 0) ? (a->yvel >> 2) : -((-a->yvel) >> 2);
      a->yvel -= 1;
      if ((sbyte)a->yvel < -12) a->yvel = -12;
      if (a->yy <= get_floor_yy(a->level)) {
        a->yy = get_floor_yy(a->level);
        a->state = WALKING;
        sound_voice(0, 0, 0, 0);
        sound_beep(0x900, 1);
      }
      break;
    default:
      break;
  }
  if (a->state == WALKING && is_in_gap(a->x, levels[a->level].gap))
    fall_down(a);
  if (do_scroll) keep_player_in_view();
}

byte read_joy(void) {
  byte j = 0;
  if (UP1) j |= 0x01;
  if (LEFT1) j |= 0x02;
  if (RIGHT1) j |= 0x04;
  if (DOWN1) j |= 0x08;
  if (FIRE1) j |= 0x10;
  return j;
}

byte check_collision(Actor* p) {
  byte i;
  for (i = 1; i < MAX_ACTORS; i++) {
    Actor* b = &actors[i];
    if (!b->onscreen) continue;
    if (p->level == b->level &&
        dist8(p->yy, b->yy) < 10 &&
        iabs8((sbyte)(p->x - b->x)) < 12)
      return 1;
  }
  return 0;
}

void play_scene(void) {
  byte i;
  for (i = 0; i < MAX_ACTORS; i++) {
    actors[i].state = INACTIVE;
    actors[i].onscreen = 0;
  }
  actors[0].state = WALKING;
  actors[0].x = 64;
  actors[0].yy = get_floor_yy(0);
  actors[0].level = 0;
  actors[0].dir = 0;
  climb_up_lock = 0;
  scroll_y = 0;
  create_actors_on_level(2);
  create_actors_on_level(4);
  wait_vblank();
  refresh_screen();

  while (actors[0].level < TOP_LEVEL) {
    wait_vblank();
    move_actor(&actors[0], read_joy(), 1);
    for (i = 1; i < MAX_ACTORS; i++) {
      byte j = 0;
      if (actors[i].state == INACTIVE) continue;
      if (actors[i].dir) j |= 0x02; else j |= 0x04;
      if ((rand8() & 31) == 0) actors[i].dir ^= 1;
      if ((rand8() & 63) == 0) j |= 0x10;
      move_actor(&actors[i], j, 0);
    }
    if (actors[0].level > 0 && check_collision(&actors[0]))
      fall_down(&actors[0]);
    draw_actors();
    draw_hud();
    watchdog = 0;
  }

  /* Standing on the yellow top floor */
  sound_beep(0x1800, 4);
  sound_beep(0x1c00, 4);
  sound_beep(0x2000, 8);
  clrscr(0);
  hide_all_sprites();
  put_string(10, 16, "YOU WIN", PAL_YELLOW);
  put_string(6, 20, "PRESS START", PAL_CYAN);
}

void main(void) {
  video_framecount = 0;
  pac_irq_enable();
  sound_enable = 1;
  flip_screen = 0;
  watchdog = 0;
  sound_off();

  for (;;) {
    clrscr(0);
    hide_all_sprites();
    put_string(8, 14, "CLIMBER", PAL_YELLOW);
    put_string(4, 18, "PRESS START", PAL_CYAN);
    put_string(2, 22, "SPACE JUMPS", PAL_PINK);
    put_string(2, 24, "REACH TOP LV", PAL_ORANGE);
    while (!START1) { wait_vblank(); watchdog = 0; }
    while (START1) { wait_vblank(); watchdog = 0; }
    make_levels();
    play_scene();
    while (!START1) { wait_vblank(); watchdog = 0; }
  }
}

