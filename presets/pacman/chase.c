byte map_at(byte x, byte y) {
  if (x >= MAP_W || y >= level_h[game_level]) return T_WALL;
  return map[y * MAP_W + x];
}

void map_set(byte x, byte y, byte t) {
  map[y * MAP_W + x] = t;
}

/* Draw one logical cell as a 2×2 tile block */
void draw_cell(byte x, byte y) {
  byte t = map_at(x, y);
  byte sx = (byte)(MAP_X0 + (x << 1));
  byte sy = (byte)(map_y0 + (y << 1));
  byte spark = (frame_cnt & 16) != 0;

  if (t == T_WALL) {
    poke_tile(sx,     sy,     T_WTL, PAL_WALL);
    poke_tile(sx + 1, sy,     T_WTR, PAL_WALL);
    poke_tile(sx,     sy + 1, T_WBL, PAL_WALL);
    poke_tile(sx + 1, sy + 1, T_WBR, PAL_WALL);
  } else if (t == T_ITEM) {
    /* Same PAL_FIELD as floor so speckles match; pens 2/3 are the gem */
    if (spark) {
      poke_tile(sx,     sy,     T_GTL2, PAL_FIELD);
      poke_tile(sx + 1, sy,     T_GTR2, PAL_FIELD);
      poke_tile(sx,     sy + 1, T_GBL2, PAL_FIELD);
      poke_tile(sx + 1, sy + 1, T_GBR2, PAL_FIELD);
    } else {
      poke_tile(sx,     sy,     T_GTL, PAL_FIELD);
      poke_tile(sx + 1, sy,     T_GTR, PAL_FIELD);
      poke_tile(sx,     sy + 1, T_GBL, PAL_FIELD);
      poke_tile(sx + 1, sy + 1, T_GBR, PAL_FIELD);
    }
  } else {
    poke_tile(sx,     sy,     T_FLOOR, PAL_FIELD);
    poke_tile(sx + 1, sy,     T_FLOOR, PAL_FIELD);
    poke_tile(sx,     sy + 1, T_FLOOR, PAL_FIELD);
    poke_tile(sx + 1, sy + 1, T_FLOOR, PAL_FIELD);
  }
}

void draw_hud(void) {
  put_string(0, 0, "LV", PAL_CYAN);
  put_digit(3, 0, game_level + 1, PAL_YELLOW);
  put_string(5, 0, "GEM", PAL_ORANGE);
  put_digit(9, 0, items_collected / 10, PAL_ORANGE);
  put_digit(10, 0, items_collected % 10, PAL_ORANGE);
  put_string(11, 0, "OF", PAL_WHITE);
  put_digit(14, 0, items_count / 10, PAL_WHITE);
  put_digit(15, 0, items_count % 10, PAL_WHITE);
  put_string(18, 0, "HP", PAL_PINK);
  put_digit(21, 0, game_lives > 0 ? (byte)(game_lives - 1) : 0, PAL_PINK);
  if (game_paused) put_string(23, 0, "PAUSE", PAL_WHITE);
  else put_string(23, 0, "     ", 0);
}

byte can_enter(byte tx, byte ty) {
  return map_at(tx, ty) != T_WALL;
}

void actor_try_dir(byte id, byte dir) {
  Actor* a = &actors[id];
  byte tx = POS_TO_TILE(a->x);
  byte ty = POS_TO_TILE(a->y);
  if (dir == DIR_LEFT) tx--;
  else if (dir == DIR_RIGHT) tx++;
  else if (dir == DIR_UP) ty--;
  else if (dir == DIR_DOWN) ty++;
  else return;
  if (!can_enter(tx, ty)) return;
  a->dir = dir;
  a->cnt = (word)TILE_PX << FP_BITS;
}

void try_collect(byte id) {
  byte tx, ty;
  Actor* a = &actors[id];
  if (id != 0 || a->wait) return;
  tx = POS_TO_TILE(a->x);
  ty = POS_TO_TILE(a->y);
  if (map_at(tx, ty) != T_ITEM) return;
  map_set(tx, ty, T_FLOOR);
  draw_cell(tx, ty);
  items_collected++;
  sfx_play(sfx_item);
  draw_hud();
}

void load_level(byte li) {
  byte x, y, i;
  byte h;
  const char* row;
  actor_n = 0;
  items_count = 0;
  items_collected = 0;
  h = level_h[li];
  /* Center 2×h tile-rows in playfield (rows 2..33) */
  map_y0 = (byte)(2 + ((32 - (h << 1)) >> 1));

  /* Clear playfield */
  for (y = 2; y < 34; y++)
    for (x = 0; x < 28; x++)
      poke_tile(x, y, T_FLOOR, PAL_FIELD);

  for (y = 0; y < h; y++) {
    row = levels[li][y];
    for (x = 0; x < MAP_W; x++) {
      char c = row[x];
      byte t = T_FLOOR;
      if (c == '#') t = T_WALL;
      else if (c == '*') { t = T_ITEM; items_count++; }
      else if (c == 'P' || c == '1' || c == '2' || c == '3') {
        Actor* a = &actors[actor_n];
        a->x = TILE_TO_POS(x);
        a->y = TILE_TO_POS(y);
        a->cnt = 0;
        a->dir = DIR_NONE;
        if (c == 'P') {
          a->kind = 0;
          a->speed = 32; /* NES player pace: 8 frames / cell */
          a->wait = 16;
        } else {
          a->kind = (byte)(c - '0');
          a->speed = (word)(10 + ((a->kind - 1) << 1));
          a->wait = (byte)(16 + (a->kind << 4));
        }
        actor_n++;
        t = T_FLOOR;
      }
      map[y * MAP_W + x] = t;
    }
  }
  for (y = 0; y < h; y++)
    for (x = 0; x < MAP_W; x++)
      draw_cell(x, y);
  for (i = actor_n; i < 8; i++) hide_sprite(i);
  spawn_wait = (byte)(actor_n << 4);
}

