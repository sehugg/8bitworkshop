byte next_music_byte(void) {
  if (!music_ptr) return 0xff;
  return *music_ptr++;
}

void sfx_stop(void) {
  sfx_ptr = 0;
  sfx_timer = 0;
  sfx_vol = 0;
  sound_voice(2, 0, 0, 0);
}

void sfx_play(const byte* seq) {
  sfx_ptr = seq;
  sfx_timer = 0; /* load first step on next update */
  sfx_vol = 0;
}

void sfx_update(void) {
  byte note, frames;
  if (!sfx_ptr) return;
  if (sfx_timer) {
    sfx_timer--;
    if (sfx_timer) return;
  }
  note = *sfx_ptr++;
  if (note == 0xff) {
    sfx_stop();
    return;
  }
  sfx_vol = *sfx_ptr++;
  frames = *sfx_ptr++;
  if (!frames) frames = 1;
  sfx_timer = frames;
  if (note & 0x80) {
    sound_voice(2, 0, 0, 0);
    sfx_vol = 0;
  } else {
    /* square — closest WSG match to NES pulse SFX */
    sound_voice(2, note_table[note & 63], sfx_vol, 1);
  }
}

void music_stop(void) {
  byte i;
  music_enable = 0;
  music_ptr = 0;
  music_loop = 0;
  chord_n = 0;
  music_release = 0;
  for (i = 0; i < MUSIC_VOICES; i++) {
    voice[i].volume = 0;
    voice_freq[i] = 0;
    sound_voice(i, 0, 0, 0);
  }
}

void music_play(const byte* music, byte loop) {
  byte i;
  music_enable = 0;
  music_paused = 0;
  music_ptr = music;
  music_loop = loop ? music : 0;
  cur_duration = 0;
  chord_n = 0;
  music_wave = 1;
  music_release = 0;
  /* Match NES Chase FamiTone $fb speed per song (NTSC tempo step 256 → 1 row / speed frames). */
  if (music == mus_game || music == mus_welldone) music_speed = 4;
  else if (music == mus_gameover) music_speed = 6;
  else music_speed = 3; /* level, clear, lose */
  for (i = 0; i < MUSIC_VOICES; i++) {
    voice[i].volume = 0;
    voice_freq[i] = 0;
    sound_voice(i, 0, 0, 0);
  }
  music_enable = 1;
}

void flush_chord(void) {
  byte bass, lead;
  /* Scores are always bass, lead pairs (0 = rest that voice). */
  bass = (chord_n >= 1) ? chord[0] : 0;
  lead = (chord_n >= 2) ? chord[1] : 0;
  chord_n = 0;

  if (bass) {
    voice_freq[0] = note_table[bass & 63];
    voice[0].volume = ENV_MAX;
    sound_voice(0, voice_freq[0], ENV_MAX, 0); /* sine bass */
    music_release = 0;
  } else if (voice_freq[0]) {
    /* Rest: keep pitch briefly, release volume (no hard mute). */
    music_release = 1;
  }
  if (lead) {
    voice_freq[1] = note_table[lead & 63];
    voice[1].volume = ENV_MAX;
    sound_voice(1, voice_freq[1], ENV_MAX, 1); /* square lead */
    music_release = 0;
  } else if (voice_freq[1]) {
    music_release = 1;
  }
  if (!bass && !lead && !voice_freq[0] && !voice_freq[1]) {
    music_release = 0;
  }
}

void music_update(void) {
  byte ch, note, floor;

  sfx_update();

  if (!music_enable || music_paused) return;

  /* Sustain while notes run; on rests, release over a few frames (not a hard cut,
   * and not a long hang). */
  floor = music_release ? 0 : ENV_SUSTAIN;
  for (ch = 0; ch < MUSIC_VOICES; ch++) {
    if (voice[ch].volume > floor) {
      /* Release twice as fast as attack sustain taper */
      voice[ch].volume -= music_release ? 2 : 1;
      if (voice[ch].volume < floor || voice[ch].volume > ENV_MAX)
        voice[ch].volume = floor;
      sound_vol(ch, voice[ch].volume);
    } else if (music_release && voice[ch].volume == 0 && voice_freq[ch]) {
      voice_freq[ch] = 0;
      sound_voice(ch, 0, 0, 0);
    }
  }

  if (!music_ptr) {
    if (music_loop) music_ptr = music_loop;
    else return;
    cur_duration = 0;
    chord_n = 0;
  }

  while (cur_duration == 0) {
    note = next_music_byte();
    if ((note & 0x80) == 0) {
      if (chord_n < 4) chord[chord_n++] = note;
    } else {
      flush_chord();
      if (note == 0xff) {
        music_ptr = music_loop;
        if (!music_ptr) { music_enable = 0; return; }
        continue;
      }
      cur_duration = (note & 63) * music_speed;
      if (!cur_duration) cur_duration = music_speed;
    }
  }
  cur_duration--;
}

