void game_loop(void) {
  byte i;

  clrscr(0);
  hide_all_sprites();
  load_level(game_level);
  draw_hud();
  game_done = 0;
  game_clear = 0;
  game_paused = 0;
  frame_cnt = 0;
  start_prev = 1;
  music_stop();

  while (!game_done) {
    wait_vblank();
    watchdog = 0;
    frame_cnt++;

    if (START1 && !start_prev) {
      game_paused = !game_paused;
      music_paused = game_paused;
      draw_hud();
    }
    start_prev = START1;
    if (game_paused) { draw_actors(); continue; }

    animate_gems();

    if (items_collected >= items_count && !game_clear) {
      game_clear = 1;
      game_done = 1;
      sfx_stop();
      music_play(mus_clear, 0);
    }

    if (spawn_wait) {
      --spawn_wait;
      if (!spawn_wait && !music_enable)
        music_play(mus_game, 1);
    }

    for (i = 0; i < actor_n; i++) {
      if (actors[i].wait) {
        if (actors[i].wait == 16)
          sfx_play(i ? sfx_respawn_e : sfx_respawn_p);
        actors[i].wait--;
        continue;
      }
      if (spawn_wait) continue;
      advance_actor(i);
      if (!actors[i].cnt) {
        if (i == 0) player_controls();
        else enemy_ai(i);
      }
    }

    draw_actors();

    if (!game_clear && hit_player()) {
      sfx_stop();
      music_play(mus_lose, 0);
      game_done = 1;
      wait_frames(100);
    }
  }
  if (game_clear) wait_frames(100);
  music_stop();
  sfx_stop();
  hide_all_sprites();
}

void main(void) {
  pac_vblank_hook = music_update;
  pac_irq_enable();
  sound_enable = 1;
  flip_screen = 0;
  watchdog = 0;
  music_enable = 0;
  music_paused = 0;
  sfx_stop();

  while (1) {
    title_screen();
    game_level = 0;
    game_lives = 4;
    while (game_lives && game_level < LEVELS_ALL) {
      show_level_banner();
      game_loop();
      if (game_clear) game_level++;
      else game_lives--;
    }
    if (!game_lives) show_game_over();
    else show_well_done();
  }
}

