byte next_music_byte(void) {
  return *music_ptr++;
}

word voice_freq[3];
byte rr_ch; /* round-robin hint for chord packing */

/* Envelope sized to the score's common 10-tick beat so notes release
 * before the next chord (avoids stolen-voice "stutter"). */
#define ENV_MAX 12

void music_update(void) {
  byte ch;
  byte n;

  if (!music_enable) return;

  /* Decay first — volume-only so frequency/phase stay stable */
  for (ch = 0; ch < 3; ch++) {
    if (voice[ch].volume) {
      voice[ch].volume--;
      sound_vol(ch, voice[ch].volume);
    }
  }

  if (!music_ptr) {
    music_ptr = music1;
    cur_duration = 0;
  }

  /* Score clock: when duration hits 0, fire all pending notes as one chord */
  while (cur_duration == 0) {
    byte note = next_music_byte();
    if ((note & 0x80) == 0) {
      word freq = note_table[note & 63];
      /* Prefer a silent/quiet channel; fall back to round-robin */
      ch = rr_ch;
      for (n = 0; n < 3; n++) {
        byte cand = (byte)((rr_ch + n) % 3);
        if (voice[cand].volume < voice[ch].volume) ch = cand;
      }
      rr_ch = ch ? (byte)(ch - 1) : 2;
      voice_freq[ch] = freq;
      voice[ch].volume = ENV_MAX;
      sound_voice(ch, freq, ENV_MAX, music_wave);
    } else {
      if (note == 0xff)
        music_ptr = 0;
      /* Duration is always >= 1 for this score; clamp just in case */
      cur_duration = note & 63;
      if (!cur_duration) cur_duration = 1;
    }
  }
  cur_duration--;
}

void music_start(const byte* music) {
  byte i;
  music_enable = 0; /* pause IRQ player while resetting */
  music_ptr = music;
  cur_duration = 0;
  rr_ch = 2;
  for (i = 0; i < 3; i++) {
    voice[i].volume = 0;
    voice_freq[i] = 0;
    sound_voice(i, 0, 0, 0);
  }
  music_enable = 1;
}

byte meter_h[3];

void draw_meters(void) {
  byte ch, h, y;
  for (ch = 0; ch < 3; ch++) {
    h = voice[ch].volume; /* 0..ENV_MAX, meter uses same scale */
    if (h == meter_h[ch]) continue;
    meter_h[ch] = h;
    for (y = 0; y < 16; y++) {
      byte row = 28 - y;
      byte on = (y < h);
      byte pal = on ? (ch == 0 ? PAL_YELLOW : (ch == 1 ? PAL_CYAN : PAL_PINK)) : 0;
      byte tile = on ? 0x11 : T_BLANK;
      poke_tile((byte)(8 + ch * 6), row, tile, pal);
      poke_tile((byte)(9 + ch * 6), row, tile, pal);
    }
  }
}

