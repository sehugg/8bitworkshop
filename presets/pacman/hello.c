/*
 * Pac-Man hardware "Hello" example for 8bitworkshop
 *
 * Uses arcade font tiles + homebrew sprites/utility tiles.
 * Graphics for this file are appended at the bottom (private copy).
 */
//#link "pacman_common.c"
#include "pacman_common.h"

void main(void) {
  byte x, y, frame;

  x = 10;
  y = 20;
  frame = 0;
  video_framecount = 0;

  pac_irq_enable();
  sound_enable = 1;
  flip_screen = 0;
  watchdog = 0;

  clrscr(0);
  hide_all_sprites();

  put_string(1, 1, "ABCDEFGHIJKLMNOPQRSTUVWX", PAL_CYAN);
  put_string(2, 2, "YZ 0123456789", PAL_PINK);
  put_string(4, 4, "HELLO PAC MAN", PAL_YELLOW);

  poke_tile(4, 8, T_DOT, PAL_ORANGE);
  poke_tile(6, 8, T_POWER, PAL_ORANGE);
  poke_tile(8, 8, T_WALL_H, PAL_BLUE);
  poke_tile(10, 8, T_WALL_V, PAL_BLUE);
  poke_tile(12, 8, T_WALL_TL, PAL_BLUE);
  poke_tile(14, 8, T_WALL_BR, PAL_BLUE);

  set_sprite(0, S_PLAYER, PAL_YELLOW, 96, 120);
  set_sprite(1, S_ALIEN, PAL_PINK, 128, 120);
  set_sprite(2, S_ALIEN, PAL_CYAN, 160, 120);

  while (1) {
    wait_vblank();
    frame++;

    poke_tile(x, y, T_BLANK, 0);

    if (UP1 && y > 2) y--;
    if (DOWN1 && y < 33) y++;
    if (LEFT1 && x > 0) x--;
    if (RIGHT1 && x < 27) x++;

    poke_tile(x, y, T_CIRCLE, PAL_YELLOW);

    poke_tile(2, 30, (byte)('0' + (frame & 7)), PAL_CYAN);
    poke_tile(24, 30, UP1    ? 'U' : T_BLANK, PAL_PINK);
    poke_tile(24, 31, RIGHT1 ? 'R' : T_BLANK, PAL_PINK);
    poke_tile(24, 32, DOWN1  ? 'D' : T_BLANK, PAL_PINK);
    poke_tile(24, 33, LEFT1  ? 'L' : T_BLANK, PAL_PINK);

    if (START1) put_string(2, 32, "START", PAL_CYAN);
    if (COIN1)  put_string(2, 34, "COIN", PAL_ORANGE);
    if (FIRE1)  put_string(2, 33, "FIRE", PAL_PINK);

    set_sprite(0, S_PLAYER, PAL_YELLOW, (byte)(x * 8), (byte)(y * 8));
  }
}

