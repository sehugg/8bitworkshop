/*
 * Pac-Man sprite demo — move hardware sprites with the joystick.
 * Graphics for this file are appended at the bottom (private copy).
 */
//#link "pacman_common.c"
#include "pacman_common.h"

void main(void) {
  byte px, py;
  byte ax, ay;
  byte frame;
  sbyte adx, ady;

  video_framecount = 0;
  pac_irq_enable();
  sound_enable = 1;
  flip_screen = 0;
  watchdog = 0;

  clrscr(0);
  hide_all_sprites();
  put_string(6, 1, "SPRITES", PAL_CYAN);
  put_string(2, 34, "MOVE WITH JOY", PAL_YELLOW);

  px = 104;
  py = 200;
  ax = 40;
  ay = 60;
  adx = 1;
  ady = 1;
  frame = 0;

  while (1) {
    wait_vblank();
    frame++;

    if (LEFT1 && px > 0) px -= 2;
    if (RIGHT1 && px < 208) px += 2;
    if (UP1 && py > 16) py -= 2;
    if (DOWN1 && py < 250) py += 2;

    ax += adx;
    ay += ady;
    if (ax < 8 || ax > 200) adx = -adx;
    if (ay < 24 || ay > 240) ady = -ady;

    set_sprite(0, S_PLAYER, PAL_YELLOW, px, py);
    set_sprite(1, S_ALIEN, PAL_PINK, ax, ay);
    set_sprite(2, S_ALIEN, PAL_CYAN, 180 - (ax >> 1), ay + 20);
    set_sprite(3, (frame & 8) ? S_BOOM1 : S_BOOM2, PAL_ORANGE, 100, 120);

    if (FIRE1)
      set_sprite(4, S_BULLET, PAL_CYAN, px + 4, py - 16);
    else
      hide_sprite(4);
  }
}

